"""Small builders shared by several test modules.

* ``kernel_sources()`` -- the OpenCL sources that PyFWI 0.1.10 generates, without
  needing an OpenCL context (for static checks of the generated ``#define`` block).
* ``tiny_case()`` and ``forward_and_gradient()`` -- a very small but complete PyFWI
  run (forward modelling + gradient) that takes well under a second on any OpenCL
  device, including POCL on a CI machine.

Only the public API of PyFWI is used by ``tiny_case``/``forward_and_gradient``,
so the same code runs in the reference environment (PyFWI 0.1.10 from PyPI)
and in the development environment (this fork).
"""
from types import SimpleNamespace

from tools.check_env import inclusion_model


def kernel_sources(order, dt=0.004 / 7, dh=7.0):
    """Return the three OpenCL sources generated by ``WavePreparation.kernel_caller``.

    ``kernel_caller`` only reads attributes of ``self``, so a ``SimpleNamespace``
    with plausible values for a 100x100 model + 20-point PML (140x140 grid),
    4 shots and 100 surface receivers is enough.

    Parameters
    ----------
    order : int
        Spatial order of the finite differences, 4 or 8 (PyFWI stores half of it).
    dt : float, optional
        Internal time step in seconds. The default is the step PyFWI uses for a
        user ``dt`` of 4 ms (split into 7 sub-steps of 0.6 ms or less).
    dh : float, optional
        Grid spacing in metres.

    Returns
    -------
    tuple of str
        Sources of ``elastic.cl``, ``elastic_crosswell.cl`` and ``elastic_surface.cl``,
        each preceded by the ``#define`` block.

    Used by
    -------
    ``test_check_env.py`` (compiles them as CUDA) and ``test_known_bugs.py``
    (inspects the generated constants).
    """
    from PyFWI.wave_propagation import WavePreparation
    fake = SimpleNamespace(sdo=order // 2, tnz=140, tnx=140, ns=4, nr=100, dt=dt, dh=dh,
                           npml=20, n_surface_rec=100, n_well_rec=0, src_cts=25,
                           rec_top_left_const=0, rec_top_left_var=0, rec_top_right_const=0,
                           rec_top_right_var=0, rec_surface_const=22, rec_surface_var=0)
    return WavePreparation.kernel_caller(fake)


def tiny_case(acq_type=1, sdo=4, components=0, ns=1, nz=40, nx=40, t=0.2, chpr=20, inpa_extra=None):
    """Build a very small PyFWI problem: model, starting model, source, receivers, propagator.

    The OpenCL device is the one selected by the ``PYOPENCL_CTX`` environment
    variable; tests set it with ``monkeypatch.setenv`` so it is restored afterwards.

    Parameters
    ----------
    acq_type : int, optional
        0 crosswell, 1 surface, 2 both (PyFWI convention).
    sdo : int, optional
        Spatial order of the finite differences, 4 or 8.
    components : int, optional
        Recorded components: 0 pressure, 1 taux, 2 vx and vz, 3 stresses, 4 all.
    ns : int, optional
        Number of sources.
    nz, nx : int, optional
        Model size in grid points (without the absorbing boundary).
    t : float, optional
        Recording length in seconds. With ``dt = 4 ms`` the propagator takes
        ``1 + t / (4 ms / 7)`` internal steps (351 for the default 0.2 s).
    chpr : int, optional
        Percentage of time steps stored as checkpoints for the gradient.
    inpa_extra : dict, optional
        Extra entries for the ``inpa`` dictionary (e.g. ``{"energy_balancing": True}``).

    Returns
    -------
    types.SimpleNamespace
        ``inpa`` (input parameters), ``model`` (true model), ``m0`` (smooth
        starting model), ``src`` (``PyFWI.acquisition.Source``), ``rec_loc``
        (receiver positions in metres, shape ``(nr, 2)``), ``n_well_rec``
        (receivers per well) and ``W`` (a ``WavePropagator``).

    Used by
    -------
    ``test_known_bugs.py``.
    """
    import PyFWI.acquisition as acq
    import PyFWI.wave_propagation as wave

    inpa = {"ns": ns, "sdo": sdo, "fdom": 15, "dh": 10, "dt": 0.004, "acq_type": acq_type,
            "t": t, "npml": 10, "pmlR": 1e-5, "pml_dir": 2, "rec_dis": 10}
    inpa.update(inpa_extra or {})
    model, m0 = inclusion_model(nz, nx), inclusion_model(nz, nx, smooth=1)
    src_loc, rec_loc, _, n_well_rec = acq.acq_parameters(ns, inpa["rec_dis"], inpa["dh"] * nx,
                                                         inpa["dh"] * nz, inpa["dh"], sdo, acq_type=acq_type)
    src = acq.Source(src_loc, inpa["dh"], inpa["dt"])
    src.Ricker(inpa["fdom"])
    W = wave.WavePropagator(inpa, src, rec_loc, (nz, nx), components=components,
                            n_well_rec=n_well_rec, chpr=chpr)
    return SimpleNamespace(inpa=inpa, model=model, m0=m0, src=src, rec_loc=rec_loc,
                           n_well_rec=n_well_rec, W=W)


def forward_and_gradient(case):
    """Run the forward modelling of the true model, then the L2 gradient at the starting model.

    Parameters
    ----------
    case : types.SimpleNamespace
        As returned by ``tiny_case()``. Its propagator ``case.W`` is used for both runs.

    Returns
    -------
    d_obs : dict[str, numpy.ndarray]
        Seismograms of the true model, one array ``(nt, nr * ns)`` per component.
    grad : dict[str, numpy.ndarray]
        Gradient with respect to ``vp``, ``vs`` and ``rho``, each ``(nz, nx)``.

    Used by
    -------
    ``test_known_bugs.py``.
    """
    import PyFWI.fwi_tools as tools
    import PyFWI.processing as process

    d_obs = process.prepare_residual(case.W.forward_modeling(case.model, False), 1)
    d_est = process.prepare_residual(case.W.forward_modeling(case.m0, False), 1)
    _, adj = tools.cost_seismic(d_est, d_obs, fun=tools.CostFunction("l2"))
    return d_obs, case.W.gradient(adj, False)
