"""Small builders shared by several test modules.

* ``kernel_sources()`` -- the OpenCL sources that PyFWI 0.1.10 generates, without
  needing an OpenCL context (for static checks of the generated ``#define`` block).
* ``tiny_case()`` and ``forward_and_gradient()`` -- a very small but complete PyFWI
  run (forward modelling + gradient) that takes well under a second on any OpenCL
  device, including POCL on a CI machine.
* ``kernel_receiver_cells()``, ``coincidences()`` and ``race_free_geometry()`` -- find
  and avoid the source and receiver positions that trigger race conditions in the
  kernels of 0.1.10.

Only the public API of PyFWI is used by ``tiny_case``/``forward_and_gradient``,
so the same code runs in the reference environment (PyFWI 0.1.10 from PyPI)
and in the development environment (this fork).
"""
import os
from types import SimpleNamespace

import numpy as np

from tools.check_env import inclusion_model


def running_reference():
    """True when the installed PyFWI is the published 0.1.10 (reference environment), not this fork.

    Bugs fixed in the fork still exist in 0.1.10, so their tests are expected to fail there:
    ``test_known_bugs.py`` uses this as the ``condition`` of their ``xfail`` markers, and
    ``test_optional_dependencies.py`` skips itself.
    """
    import PyFWI  # imported here so that importing this module never needs PyFWI
    repository = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    return PyFWI.__version__ == "0.1.10" and not os.path.abspath(PyFWI.__file__).startswith(repository + os.sep)


#: Bits (float32 viewed as uint32) of ``fwi_tools.pml_delta_calculation(np.float32(10.0), 10, 1e-5)``
#: in PyFWI 0.1.10 with NumPy 1.21: the damping profile of a 10-point PML with a 10 m grid.
#: NumPy 2 changed the type promotion of ``n_pml * dh`` and ``3 / (2 * delta1)`` (NEP 50) and
#: gives a different last bit in 3 of the 10 values.
PML_REFERENCE_BITS = (0, 977574822, 994352038, 1004351259, 1011129254, 1016699290,
                      1021128475, 1024886571, 1027906470, 1031329022)


def pml_matches_0_1_10():
    """True if the installed PyFWI computes the PML profile of 0.1.10 bit for bit.

    The PML profile is the only input of the kernels that differs between the
    reference environment and current NumPy, so this decides whether results can be
    compared with the golden masters bit for bit.

    Used by ``test_characterization.py`` and ``test_known_bugs.py``.
    """
    import PyFWI.fwi_tools as tools
    profile = np.asarray(tools.pml_delta_calculation(np.float32(10.0), 10, 1e-5), np.float32)
    return tuple(int(b) for b in profile.view(np.uint32)) == PML_REFERENCE_BITS


def kernel_sources(order, dt=0.004 / 7, dh=7.0, numerics="legacy"):
    """Return the three OpenCL sources generated by ``WavePreparation.kernel_caller``.

    ``kernel_caller`` only reads attributes of ``self``, so a ``SimpleNamespace``
    with plausible values for a 100x100 model + 20-point PML (140x140 grid),
    4 shots and 100 surface receivers is enough.

    Parameters
    ----------
    order : int
        Spatial order of the finite differences, 4 or 8 (PyFWI stores half of it).
    dt : float, optional
        Internal time step in seconds. The default is the step PyFWI uses for a
        user ``dt`` of 4 ms (split into 7 sub-steps of 0.6 ms or less).
    dh : float, optional
        Grid spacing in metres.
    numerics : str, optional
        Numeric mode of the fork (step 2.4): ``"legacy"`` (the sources of 0.1.10) or ``"fixed"``.
        The published 0.1.10 ignores it.

    Returns
    -------
    tuple of str
        Sources of ``elastic.cl``, ``elastic_crosswell.cl`` and ``elastic_surface.cl``,
        each preceded by the ``#define`` block.

    Used by
    -------
    ``test_check_env.py`` (compiles them as CUDA) and ``test_known_bugs.py``
    (inspects the generated constants).
    """
    from PyFWI.wave_propagation import WavePreparation
    fake = SimpleNamespace(sdo=order // 2, tnz=140, tnx=140, ns=4, nr=100, dt=dt, dh=dh,
                           npml=20, n_surface_rec=100, n_well_rec=0, src_cts=25,
                           rec_top_left_const=0, rec_top_left_var=0, rec_top_right_const=0,
                           rec_top_right_var=0, rec_surface_const=22, rec_surface_var=0, numerics=numerics)
    return WavePreparation.kernel_caller(fake)


